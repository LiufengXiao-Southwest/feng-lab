# ── Journal quality gate ─────────────────────────────────────────────────────
# Metrics come from data/journals.json, regenerated by
# scripts/update_journal_metrics.py from OpenAlex + the curated data/jcr_seed.json.
#
# This replaced a hardcoded dict that matched venues by loose substring, which
# had two consequences: "International Journal of Sports Medicine" inherited
# "Sports Medicine"'s IF of 9.8 (39 of 190 archived papers carried that wrong
# number), and any journal absent from the dict was silently discarded.
JOURNALS = JournalIndex.load()

MIN_IF = 3.0            # curated JCR floor
MIN_OPENALEX_2YR = 2.0  # OpenAlex runs lower than JCR, so it gets its own floor


def _always_include() -> set[str]:
    """Journals the lab wants regardless of what the thresholds say.

    Editorial preference, kept separate from the metric gate so the two do not
    get confused. Gait & Posture sits here: IF 2.7 and JCR Q2, but it is a core
    venue for this lab's biomechanics work.
    """
    seed = Path(__file__).parent.parent / "data" / "jcr_seed.json"
    if not seed.exists():
        return set()
    try:
        payload = json.loads(seed.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return set()
    from journal_metrics import normalize_name
    return {normalize_name(n) for n in payload.get("always_include", []) if n}


ALWAYS_INCLUDE = _always_include()
_RESOLVED_LIVE = []   # journals discovered this run, persisted at the end
_UNRESOLVED = set()   # venues that failed this run; do not retry within the run

# A run screens up to ~270 candidates and most rejected venues are conference
# proceedings or predatory titles that no source will ever resolve. Without a
# ceiling, one bad day of results could spend a large slice of the easyScholar
# daily quota on journals that will never be published.
MAX_LIVE_LOOKUPS = 25


def _passes_gate(entry: dict) -> bool:
    """Is this journal good enough for the digest?

    Any one of these is enough — a journal can be excellent in its own field
    while sitting below the sport-science impact floor:
      * impact factor >= MIN_IF
      * JCR or SJR quartile Q1
      * CAS (中科院) tier 1区 or 2区 in any sub-category
      * on the always-include list
      * failing all of the above, a fallback citation metric above the floor
    """
    from journal_metrics import normalize_name

    if entry.get("is_preprint_server"):
        return False  # a preprint server reached a journal query; not a journal
    if normalize_name(entry.get("name", "")) in ALWAYS_INCLUDE:
        return True

    try:
        if float(entry.get("jcr_if") or 0) >= MIN_IF:
            return True
    except (TypeError, ValueError):
        pass

    if "Q1" in (entry.get("jcr_quartile") or "", entry.get("sjr_quartile") or ""):
        return True

    cas = f"{entry.get('cas_tier_small') or ''} {entry.get('cas_tier') or ''}"
    if "1区" in cas or "2区" in cas:
        return True

    if not entry.get("jcr_if"):
        # This is the weakest tier: no impact factor, no quartile, no CAS tier —
        # only a citation rate. A citation rate says nothing about subject, and
        # Photonics (OpenAlex 2yr 2.2) cleared it into a sports-science digest.
        # Journals reaching this branch must also be placeable in the field.
        if not is_domain_relevant(entry):
            return False
        for field, floor in (("cite_doc_2y", MIN_IF), ("openalex_2yr", MIN_OPENALEX_2YR)):
            try:
                if float(entry.get(field) or 0) >= floor:
                    return True
            except (TypeError, ValueError):
                continue
    return False


def lookup_journal(venue: str, issns=()):
    """Resolve a venue to (entry, if_display, if_source, passes_gate).

    On a cache miss the journal is resolved live rather than discarded. The old
    lookup treated "not in my hardcoded dict" as "not Q1", so the digest could
    never surface a paper from Nature, The Lancet or J Physiol no matter how
    good it was.
    """
    entry = JOURNALS.lookup(venue, issns)

    if not entry and venue:
        from journal_metrics import normalize_name
        key = normalize_name(venue)
        # Skip venues already tried and skip further lookups once the budget is
        # spent — otherwise the same unresolvable venue is re-queried on every
        # candidate that carries it, and again tomorrow.
        # Budget counts attempts, not successes: a failed lookup costs the same
        # API calls as a successful one, and the first full-pool run spent 40
        # lookups against a stated cap of 25 because only the hits were counted.
        if (key in _UNRESOLVED
                or JOURNALS.is_unresolved(venue)
                or len(_RESOLVED_LIVE) + len(_UNRESOLVED) >= MAX_LIVE_LOOKUPS):
            return None, "", "", False
        try:
            from update_journal_metrics import resolve_live
            entry = resolve_live(venue, list(issns))
        except Exception as e:                       # noqa: BLE001
            print(f"    [!] live lookup failed for '{venue[:40]}': {e}")
            entry = None
        if entry:
            JOURNALS.add(entry)
            _RESOLVED_LIVE.append(entry["name"])
            print(f"    + resolved new journal: {entry['name'][:50]}")
        else:
            _UNRESOLVED.add(key)
            JOURNALS.mark_unresolved(venue)

    if not entry:
        return None, "", "", False

    if_display, if_source = display_impact(entry)
    return entry, if_display, if_source, _passes_gate(entry)

