SS_URL    = "https://api.semanticscholar.org/graph/v1/paper/search"
SS_FIELDS = (
    "title,authors,year,abstract,externalIds,publicationDate,"
    "venue,publicationVenue,publicationTypes,tldr,"
    "isOpenAccess,openAccessPdf,citationCount"
)
# Without a key, Semantic Scholar's search endpoint shares one pool across all
# anonymous callers and returns 429 often enough to silently empty a daily run.
SS_API_KEY = os.environ.get("SEMANTIC_SCHOLAR_API_KEY", "")


# Measured 2026-07-29: with a key, 2 of 8 search calls spaced 3s apart still
# returned 429 — well short of the documented 1 rps, so the endpoint is simply
# flaky. Without a key it was 0 of 8. More attempts, with the delay capped so a
# bad run cannot stretch the job indefinitely.
SS_TRIES = 6
SS_MAX_DELAY = 15.0


def ss_get(params: dict, tries: int = SS_TRIES):
    """GET the search endpoint with capped exponential backoff on 429/5xx."""
    headers = {"x-api-key": SS_API_KEY} if SS_API_KEY else {}
    delay = 2.0
    for attempt in range(tries):
        try:
            r = requests.get(SS_URL, params=params, headers=headers, timeout=25)
            if r.status_code == 429 or r.status_code >= 500:
                if attempt == tries - 1:
                    print(f"    [!] giving up after {tries} tries (HTTP {r.status_code})")
                    return None
                print(f"    ... HTTP {r.status_code}, retrying in {delay:.0f}s")
                time.sleep(delay)
                delay = min(delay * 2, SS_MAX_DELAY)
                continue
            r.raise_for_status()
            return r.json()
        except requests.RequestException as e:
            if attempt == tries - 1:
                print(f"    [!] request failed: {e}")
                return None
            time.sleep(delay)
            delay = min(delay * 2, SS_MAX_DELAY)
    return None

# ── Fetch ─────────────────────────────────────────────────────────────────────
def fetch_ss(query: str, category: str, limit: int = 10) -> list:
    """Fetch papers from Semantic Scholar.
    For non-preprint categories, only papers from JCR Q1 journals (IF >= MIN_IF)
    are kept.  Preprint papers are passed through without journal filtering.
    """
    papers = []
    is_preprint = (category == "preprint")

    data = ss_get({
        "query": query,
        "fields": SS_FIELDS,
        "limit": limit,
        "publicationDateOrYear": f"{datetime.date.today().year - 3}:",
    })
    if data is None:
        return papers

    accepted = rejected_if = rejected_abs = 0

    for p in data.get("data", []):
        title    = (p.get("title") or "").strip()
        abstract = (p.get("abstract") or "").strip()
        if not title or not abstract or len(abstract) < 80:
            rejected_abs += 1
            continue

        pv = p.get("publicationVenue") or {}
        venue = (pv.get("name") or p.get("venue") or "").strip()
        issns = pv.get("issn") or []
        if isinstance(issns, str):
            issns = [issns]

        entry, if_val, if_source, passes = lookup_journal(venue, issns)

        if is_preprint:
            # Only keep things that really are preprints, so this category stops
            # acting as a bypass for journals that failed the quality gate.
            if not _looks_like_preprint(p, entry, venue):
                rejected_if += 1
                continue
        elif not passes:
            rejected_if += 1
            continue

        doi      = p.get("externalIds", {}).get("DOI", "")
        authors  = [a.get("name", "") for a in (p.get("authors") or [])[:5]]
        is_oa    = bool(p.get("isOpenAccess"))
        oa_pdf   = p.get("openAccessPdf") or {}
        pdf_url  = oa_pdf.get("url", "") if isinstance(oa_pdf, dict) else ""
        citations = p.get("citationCount") or 0
        tldr     = (p.get("tldr") or {}).get("text", "") if isinstance(p.get("tldr"), dict) else ""

        papers.append({
            "id": hashlib.md5((title + str(p.get("year", ""))).encode()).hexdigest()[:8],
            "title_en":       title,
            "title_zh":       "",
            "authors":        authors,
            "journal":        entry.get("name") if entry else venue,
            "journal_issn":   (entry.get("issn") or [""])[0] if entry else "",
            "year":           (p.get("year") or datetime.date.today().year),
            "date_added":     TODAY,
            "category":       category,
            "doi":            doi,
            "impact_factor":  if_val,
            "if_source":      if_source,
            "journal_tier":   display_tier(entry),
            "evidence":       _evidence_level(p),
            "citation_count": citations,
            "is_open_access": is_oa,
            "pdf_url":        pdf_url,
            "tldr_en":        tldr,
            "tldr_zh":        "",
            "abstract_en":    abstract[:900],
            "abstract_zh":    "",
            "keywords":       [],
        })
        accepted += 1

    print(f"    accepted={accepted}, rejected(journal gate)={rejected_if}, rejected(no abs)={rejected_abs}")
    time.sleep(1.2 if SS_API_KEY else 3.0)
    return papers


def _looks_like_preprint(paper: dict, entry: dict | None, venue: str) -> bool:
    if entry and entry.get("is_preprint_server"):
        return True
    doi = (paper.get("externalIds") or {}).get("DOI", "") or ""
    if doi.startswith("10.1101/") or doi.startswith("10.51224/"):  # bioRxiv/medRxiv, SportRxiv
        return True
    if (paper.get("externalIds") or {}).get("ArXiv"):
        return True
    return any(k in venue.lower() for k in ("biorxiv", "medrxiv", "sportrxiv", "arxiv", "preprint"))


# Sports-science readers filter on study design before anything else, so surface
# it as a first-class field rather than making them read the abstract to find it.
_EVIDENCE_ORDER = [
    ("MetaAnalysis",   "meta"),
    ("Review",         "review"),
    ("ClinicalTrial",  "trial"),
]


def _evidence_level(paper: dict) -> str:
    types = paper.get("publicationTypes") or []
    for ss_type, label in _EVIDENCE_ORDER:
        if ss_type in types:
            return label
    return ""


# ── Deduplication ─────────────────────────────────────────────────────────────
def dedupe(papers: list) -> list:
    seen, result = set(), []
    for p in papers:
        key = (p.get("doi") or "").strip() or p.get("title_en", "").lower()[:60]
        if key and key not in seen:
            seen.add(key)
            result.append(p)
    return result


def impact_factor_value(paper: dict) -> float:
    try:
        return float(paper.get("impact_factor") or 0)
    except (TypeError, ValueError):
        return 0.0


def paper_score(paper: dict, today: datetime.date | None = None) -> float:
    """Rank papers for a *daily* digest.

    Sorting by raw citation count — the previous behaviour — structurally
    favours the oldest paper in the window, because citations only accumulate.
    A 2023 paper with 40 citations always outranked anything published this
    month, so the "daily digest" mostly resurfaced three-year-old work.

    Citations are therefore divided by the paper's age to get a citation *rate*,
    and a recency bonus keeps genuinely new work visible before it has had time
    to be cited at all.
    """
    today = today or datetime.date.today()
    year = paper.get("year") or today.year
    age = max(today.year - int(year) + 0.5, 0.5)   # 0.5 for the current year

    citations = paper.get("citation_count") or 0
    citation_rate = citations / age

    impact = impact_factor_value(paper)

    # Diminishing returns: the gap between 0 and 10 citations/year matters far
    # more than the gap between 90 and 100.
    def damp(x: float) -> float:
        return math.log1p(max(x, 0))

    recency_bonus = {0: 3.0, 1: 1.5, 2: 0.5}.get(today.year - int(year), 0.0)
    # Meta-analyses and systematic reviews carry more weight per paper than a
    # single trial, which is how this audience reads a digest.
    evidence_bonus = {"meta": 1.2, "review": 0.8, "trial": 0.5}.get(
        paper.get("evidence") or "", 0.0)

    return (2.0 * damp(citation_rate)
            + 1.0 * damp(impact)
            + recency_bonus
            + evidence_bonus)


RECENT_WINDOW_DAYS = 30


def recently_published(archive_file: Path = ARCHIVE_FILE,
                       days: int = RECENT_WINDOW_DAYS,
                       today: datetime.date | None = None) -> set:
    """Keys (DOI or id) published in the last `days` days.

    The fetcher had no memory of what it had already shown, and the same query
    returns the same top-ranked papers day after day, so the digest repeated
    itself: 190 archived entries covered only 66 distinct papers, some appearing
    seven times. A reader checking daily mostly saw yesterday's list again.
    """
    if not archive_file.exists():
        return set()
    try:
        archive = json.loads(archive_file.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return set()

    today = today or datetime.date.today()
    cutoff = (today - datetime.timedelta(days=days)).isoformat()

    seen = set()
    for date, papers in (archive.get("dates") or {}).items():
        if date < cutoff:
            continue
        for p in papers:
            doi = (p.get("doi") or "").strip().lower()
            if doi:
                seen.add(doi)
            if p.get("id"):
                seen.add(p["id"])
    return seen


def select_top_daily_papers(papers: list, limit: int = DAILY_LIMIT,
                            exclude: set | None = None) -> list:
    """Select the best papers across all categories, skipping recent repeats.

    If filtering leaves too few papers, the excluded ones are added back rather
    than shipping a near-empty digest — a repeat beats an empty page.
    """
    unique = dedupe(papers)
    exclude = exclude if exclude is not None else recently_published()

    def key_of(p):
        return (p.get("doi") or "").strip().lower() or p.get("id") or ""

    fresh = [p for p in unique if key_of(p) not in exclude]
    ranked = sorted(fresh, key=paper_score, reverse=True)

    if len(ranked) < limit:
        repeats = sorted((p for p in unique if key_of(p) in exclude),
                         key=paper_score, reverse=True)
        skipped = len(unique) - len(fresh)
        if repeats:
            print(f"  [i] Only {len(ranked)} fresh papers; backfilling from "
                  f"{skipped} recently-shown ones.")
        ranked += repeats

    return ranked[:limit]


def write_daily_outputs(papers: list, data_file: Path = DATA_FILE, archive_file: Path = ARCHIVE_FILE, today=None) -> None:
    date_str = (today or datetime.date.today()).isoformat()
    today_papers = []
    for paper in papers:
        item = dict(paper)
        item["date_added"] = date_str
        today_papers.append(item)

    data_file.parent.mkdir(parents=True, exist_ok=True)
    with open(data_file, "w", encoding="utf-8") as f:
        json.dump({"last_updated": date_str, "papers": today_papers}, f, ensure_ascii=False, indent=2)

    archive = {"last_updated": date_str, "dates": {}}
    if archive_file.exists():
        with open(archive_file, "r", encoding="utf-8") as f:
            archive = json.load(f)
        archive.setdefault("dates", {})

    archive["last_updated"] = date_str
    archive["dates"][date_str] = today_papers
    with open(archive_file, "w", encoding="utf-8") as f:
        json.dump(archive, f, ensure_ascii=False, indent=2)


# ── Gemini translation ────────────────────────────────────────────────────────
def translate_papers(papers: list) -> list:
    """Fill title_zh and abstract_zh for papers missing translations."""
    api_key = os.environ.get("GEMINI_API_KEY", "")
    if not api_key:
        print("  [!] GEMINI_API_KEY not set, skipping translation.")
        return papers

    to_translate = [p for p in papers if not p.get("title_zh") or not p.get("abstract_zh")]
    if not to_translate:
        print(f"  All papers already have translations.")
        return papers

    print(f"  Translating {len(to_translate)} papers via Gemini...")

    # Process in batches of 6 to stay within token limits
    BATCH = 6
    for start in range(0, len(to_translate), BATCH):
        batch = to_translate[start:start + BATCH]
        items = "\n\n".join([
            f"{i+1}. Title: {p['title_en']}\nAbstract: {p['abstract_en'][:600]}"
            for i, p in enumerate(batch)
        ])
        prompt = (
            f"Translate the following {len(batch)} academic paper titles and abstracts "
            f"into Chinese. Return ONLY a JSON array with {len(batch)} objects, "
            f'each with "title_zh" and "abstract_zh" fields. '
            f"Keep translations accurate and academic.\n\n{items}"
        )
        try:
            import google.generativeai as genai
            genai.configure(api_key=api_key)
            model = genai.GenerativeModel("gemini-2.5-flash")
            resp = model.generate_content(prompt)
            raw = resp.text.strip()
            if raw.startswith("```"):
                raw = raw.split("```")[1]
                if raw.startswith("json"):
                    raw = raw[4:]
            translations = json.loads(raw.strip())
            for i, p in enumerate(batch):
                if i < len(translations):
                    p["title_zh"]    = translations[i].get("title_zh", "")
                    p["abstract_zh"] = translations[i].get("abstract_zh", "")
            print(f"    Batch {start//BATCH + 1}: {len(batch)} translated ✓")
        except Exception as e:
            print(f"    [!] Translation batch error: {e}")
        time.sleep(2)

    return papers


# ── Main ──────────────────────────────────────────────────────────────────────
def main():
    print(f"FENG LAB — Daily fetch  [{TODAY}]")

    # Fetch new papers
    # Use larger per-query limit (15) because Q1 filtering discards many results
    new_papers = []
    for category, queries in SEARCHES.items():
        print(f"\n▸ {category} (Q1/IF≥{MIN_IF} filter: {'off' if category == 'preprint' else 'on'})")
        for q in queries:
            print(f"  query: {q[:65]}...")
            fetched = fetch_ss(q, category, limit=15)
            new_papers.extend(fetched)

    print(f"\nNew papers collected: {len(new_papers)}")
    selected_papers = select_top_daily_papers(new_papers)
    print(f"Top papers selected: {len(selected_papers)}")

    # Translate new papers that are missing translations
    selected_papers = translate_papers(selected_papers)
    write_daily_outputs(selected_papers)

    # Persist journals discovered during this run so the next one starts warm
    # and the metrics cache grows with the site instead of being capped.
    if _RESOLVED_LIVE or _UNRESOLVED:
        JOURNALS.save()
        if _RESOLVED_LIVE:
            print(f"\n  Cached {len(_RESOLVED_LIVE)} newly-resolved journals: "
                  f"{', '.join(_RESOLVED_LIVE[:5])}"
                  f"{' …' if len(_RESOLVED_LIVE) > 5 else ''}")
        if _UNRESOLVED:
            print(f"  Remembered {len(_UNRESOLVED)} unresolvable venues "
                  f"so they are not re-queried tomorrow.")

    print(f"\n✓ Done. Today's papers: {len(selected_papers)}")


if __name__ == "__main__":
    main()
